import { useMemo, useState } from 'react';
import {
  Stack, Box, Typography, Button, Breadcrumbs, Link as MuiLink, Paper, TextField, InputAdornment,
} from '@mui/material';
import { Link as RouterLink } from 'react-router-dom';
import NavigateNextIcon from '@mui/icons-material/NavigateNext';
import ArrowBackOutlinedIcon from '@mui/icons-material/ArrowBackOutlined';
import SearchOutlinedIcon from '@mui/icons-material/SearchOutlined';

import DataTable from '../../components/common/DataTable';
import BarcodeImage from './components/BarcodeImage';
import { useBarcodeHistoryQuery } from '../../api/barcodeLabelApi';

const BARCODE_TYPE_LABEL = {
  'ean-13': 'EAN-13', 'code-128': 'CODE-128', 'upc-a': 'UPC-A', qr: 'QR',
};

const MONTH_NAMES = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

function formatDateTime(value) {
  if (!value) return '-';
  const d = new Date(value);
  const time = d.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
  return `${String(d.getDate()).padStart(2, '0')} ${MONTH_NAMES[d.getMonth()]} ${d.getFullYear()}, ${time}`;
}

/**
 * Append-only "Barcode History" log — every barcode value that has ever
 * actually been generated for print (see barcodeLabel.service.js's
 * generateBarcodesForBatch), one row per item per generation, newest
 * first, each with its own real scannable barcode/QR thumbnail (see
 * BarcodeImage). Separate from the batch list it sits behind: a batch can
 * still be edited or deleted afterwards, but once a barcode has actually
 * been generated from it, its entry here stays put. Reached via the
 * "Barcode History" button on the Barcode & Label list pages (see
 * BarcodeLabelPage's 'history' tab).
 */
export default function BarcodeHistoryPage({ onBack }) {
  const [search, setSearch] = useState('');
  const { data: rows = [], isLoading, isError } = useBarcodeHistoryQuery({ search: search || undefined });

  const columns = useMemo(() => [
    { key: 'index', label: '#', render: (_row, i) => i + 1 },
    { key: 'createdAt', label: 'Generated On', render: (row) => formatDateTime(row.createdAt) },
    { key: 'batchCode', label: 'Batch No.' },
    { key: 'itemCode', label: 'Item Code' },
    { key: 'itemName', label: 'Item Name' },
    {
      key: 'barcodeValue',
      label: 'Barcode',
      render: (row) => <BarcodeImage value={row.barcodeValue} barcodeType={row.barcodeType} height={44} width={130} />,
    },
    { key: 'barcodeType', label: 'Type', render: (row) => BARCODE_TYPE_LABEL[row.barcodeType] || row.barcodeType },
    { key: 'printQty', label: 'Print Qty', align: 'right', render: (row) => Number(row.printQty).toFixed(2) },
    { key: 'generatedBy', label: 'Generated By' },
  ], []);

  return (
    <Stack spacing={2}>
      <Stack direction={{ xs: 'column', sm: 'row' }} spacing={1.5} sx={{ alignItems: { xs: 'flex-start', sm: 'center' }, justifyContent: 'space-between' }}>
        <Box>
          <Typography variant="h6" sx={{ fontWeight: 800 }}>Barcode History</Typography>
          <Breadcrumbs separator={<NavigateNextIcon sx={{ fontSize: 14 }} />} sx={{ '& .MuiTypography-root, & .MuiLink-root': { fontSize: 12.5 } }}>
            <MuiLink component={RouterLink} to="/home" underline="hover" color="text.secondary">Home</MuiLink>
            <MuiLink component={RouterLink} to="/barcode-label" underline="hover" color="text.secondary">Barcode &amp; Label</MuiLink>
            <Typography variant="caption" sx={{ color: 'text.secondary' }}>History</Typography>
          </Breadcrumbs>
        </Box>
        <Button variant="outlined" color="inherit" startIcon={<ArrowBackOutlinedIcon fontSize="small" />} onClick={onBack}>
          Back to Batch List
        </Button>
      </Stack>

      <Paper variant="outlined" sx={{ borderRadius: 3 }}>
        <Box sx={{ p: 2 }}>
          <TextField
            fullWidth
            size="small"
            placeholder="Search by item code, item name, barcode or batch no…"
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            slotProps={{
              input: {
                startAdornment: (
                  <InputAdornment position="start">
                    <SearchOutlinedIcon fontSize="small" sx={{ color: 'text.secondary' }} />
                  </InputAdornment>
                ),
              },
            }}
          />
        </Box>
        <Box sx={{ px: 2, pb: 2, overflow: 'auto' }}>
          {isLoading ? (
            <Typography variant="body2" sx={{ color: 'text.secondary', p: 2 }}>Loading history…</Typography>
          ) : isError ? (
            <Typography variant="body2" color="error" sx={{ p: 2 }}>Failed to load barcode history.</Typography>
          ) : (
            <DataTable
              columns={columns}
              rows={rows}
              getRowKey={(r) => r.id}
              emptyMessage="No barcodes generated yet — generate one from a batch's Print / Preview to get started."
            />
          )}
        </Box>
      </Paper>
    </Stack>
  );
}
