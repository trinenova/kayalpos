import { z } from 'zod';

// One cart line of a held bill. Like the sale schema, only productId + qty
// are trusted — name/uom/price/taxRate are re-read from the Product row on
// the server, never taken from the client.
const heldBillLineSchema = z.object({
  productId: z.string().trim().min(1, 'Product is required'),
  qty: z.coerce.number().positive('Quantity must be greater than 0').max(999999, 'Quantity is too large')
    .refine((n) => Math.abs(n * 1000 - Math.round(n * 1000)) < 1e-6, 'Quantity can have at most 3 decimal places'),
  // Unit the qty was typed in; converted to the item group's base unit on save.
  uom: z.string().trim().min(1).max(50).optional().nullable(),
  // Product barcode the item was scanned with (its own price / UOM apply).
  barcode: z.string().trim().min(1).max(100).optional().nullable(),
});

export const holdBillSchema = z.object({
  customerId: z.string().trim().min(1).optional().nullable(),
  customerName: z.string().trim().min(1).default('Walk-in Customer'),
  lines: z.array(heldBillLineSchema).min(1, 'Add at least one item before holding the bill'),
  discountType: z.enum(['amount', 'percent']).default('amount'),
  discountValue: z.coerce.number().nonnegative('Discount cannot be negative').default(0),
  // Idempotency token generated by the client for one hold attempt (see
  // HeldBill.clientToken in schema.prisma). Only used on create.
  clientToken: z.string().trim().min(8).max(64).optional(),
}).refine((v) => v.discountType !== 'percent' || v.discountValue <= 100, {
  path: ['discountValue'],
  message: 'Percentage discount cannot exceed 100',
});
