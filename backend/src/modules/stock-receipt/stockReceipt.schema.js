import { z } from 'zod';

// One line-item row from the Create Stock Receipt form's item grid. Every
// filled row (itemCode non-blank) is part of the document — same "every
// filled row counts" convention Stock Indent/Stock Transfer use. Unlike
// those two modules, orderedQty/receivedQty/unitCost/discount/tax are all
// accepted as-is from the client — they're the real figures the user typed
// off the supplier's invoice/GRN, not values fabricated from a Product
// master lookup. Only `totalCost` is never accepted from the client — that's
// always recomputed server-side (see stockReceipt.service.js's computeItems)
// so a client can never fabricate its own line total.
const itemRowSchema = z.object({
  itemCode: z.string().trim().min(1, 'Item code is required'),
  itemName: z.string().trim().min(1, 'Item name is required'),
  hsnCode: z.string().trim().optional().or(z.literal('')),
  barcode: z.string().trim().optional().or(z.literal('')),
  uom: z.string().trim().optional().or(z.literal('')),
  orderedQty: z.coerce.number().min(0, 'Ordered qty cannot be negative').default(0),
  receivedQty: z.coerce.number().positive('Received qty must be greater than 0'),
  unitCost: z.coerce.number().min(0, 'Unit cost cannot be negative').default(0),
  discount: z.coerce.number().min(0, 'Discount cannot be negative').max(100, 'Discount cannot exceed 100%').default(0),
  tax: z.coerce.number().min(0, 'Tax cannot be negative').max(100, 'Tax cannot exceed 100%').default(0),
  warehouse: z.string().trim().optional().or(z.literal('')),
  batchNo: z.string().trim().optional().or(z.literal('')),
  expiryDate: z.coerce.date().optional().nullable(),
  remarks: z.string().trim().optional().or(z.literal('')),
});

// `code` is auto-generated by the service (RCPT-00001, RCPT-00002, ...)
// unless the client supplies one explicitly — same convention as every
// other module. `supplierId`/`fromOutletId` are validated against real
// Supplier/Outlet rows for this tenant in the service layer (not here — Zod
// only checks shape, not database existence). `status` only ever accepts
// 'draft' or 'received' here, matching the reference design's own two-state
// Draft/Received goods-receiving lifecycle — there's no separate "in
// transit"/approval step for a receipt the way Stock Transfer/Stock Indent
// have, since receiving is the terminal step of the goods-movement chain.
export const createStockReceiptSchema = z.object({
  code: z.string().trim().min(1).optional(),
  receiptDate: z.coerce.date(),
  purchaseType: z.string().trim().min(1, 'Purchase type is required'),
  purchaseInvoiceNo: z.string().trim().optional().or(z.literal('')),
  purchaseInvoiceDate: z.coerce.date().optional().nullable(),
  grnDcNo: z.string().trim().optional().or(z.literal('')),
  grnDcDate: z.coerce.date().optional().nullable(),
  receiptRemarks: z.string().trim().optional().or(z.literal('')),
  supplierId: z.string().trim().min(1, 'Supplier is required'),
  fromOutletId: z.string().trim().min(1, 'From Outlet / HO is required'),
  costCenter: z.string().trim().optional().or(z.literal('')),
  contactPerson: z.string().trim().optional().or(z.literal('')),
  mobileNo: z.string().trim().optional().or(z.literal('')),
  referenceNo: z.string().trim().optional().or(z.literal('')),
  vehicleNo: z.string().trim().optional().or(z.literal('')),
  transporter: z.string().trim().optional().or(z.literal('')),
  deliveryChallanNo: z.string().trim().optional().or(z.literal('')),
  otherRemarks: z.string().trim().optional().or(z.literal('')),
  notes: z.string().trim().optional().or(z.literal('')),
  status: z.enum(['draft', 'received']).default('draft'),
  items: z.array(itemRowSchema).min(1, 'Add at least one item'),
});

// Edit mode always resubmits the whole form (see CreateStockReceiptPage), so
// the update schema keeps the same full validation instead of `.partial()`
// — same convention as Stock Indent/Stock Transfer.
export const updateStockReceiptSchema = createStockReceiptSchema;
